CREATE TABLE IF NOT EXISTS discovery_users (
  user_id TEXT PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  full_name TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'advisor',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS discovery_leads (
  id TEXT PRIMARY KEY,
  team TEXT NOT NULL,
  owner_user_id TEXT NOT NULL,
  owner_email TEXT NOT NULL,
  payload TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_discovery_leads_team_updated
ON discovery_leads(team, updated_at DESC);

CREATE INDEX IF NOT EXISTS idx_discovery_leads_team_owner
ON discovery_leads(team, owner_user_id);

CREATE TABLE IF NOT EXISTS discovery_campaigns (
  id TEXT PRIMARY KEY,
  team TEXT NOT NULL,
  created_by_user_id TEXT NOT NULL,
  payload TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_discovery_campaigns_team_updated
ON discovery_campaigns(team, updated_at DESC);

CREATE TABLE IF NOT EXISTS discovery_jobs (
  id TEXT PRIMARY KEY,
  team TEXT NOT NULL,
  campaign_id TEXT NOT NULL,
  requested_by_user_id TEXT NOT NULL,
  payload TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_discovery_jobs_team_campaign_updated
ON discovery_jobs(team, campaign_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS discovery_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team TEXT NOT NULL,
  actor_user_id TEXT NOT NULL,
  actor_email TEXT NOT NULL,
  action TEXT NOT NULL,
  record_type TEXT NOT NULL,
  record_id TEXT NOT NULL,
  detail TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_discovery_audit_team_created
ON discovery_audit(team, created_at DESC);



CREATE TABLE IF NOT EXISTS lead_call_records (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  lead_id TEXT NOT NULL,
  week_start TEXT NOT NULL,
  outcome TEXT NOT NULL,
  notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_call_user_week ON lead_call_records(user_id, week_start);
CREATE TABLE IF NOT EXISTS lead_call_blocks (
  phone TEXT PRIMARY KEY,
  lead_id TEXT NOT NULL,
  user_id TEXT NOT NULL,
  reason TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS lead_call_preferences (
  user_id TEXT PRIMARY KEY,
  location TEXT NOT NULL DEFAULT 'Long Island',
  age_focus TEXT NOT NULL DEFAULT 'all',
  timely_focus TEXT NOT NULL DEFAULT 'all',
  ideal_prospect TEXT NOT NULL DEFAULT '',
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS enrichment_batches (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  provider TEXT NOT NULL CHECK(provider IN ('zoominfo','wealthfeed')),
  status TEXT NOT NULL CHECK(status IN ('awaiting_upload','preview','complete')),
  payload TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS enrichment_batches_user ON enrichment_batches(user_id);
CREATE TABLE IF NOT EXISTS enrichment_commit_guards (id TEXT PRIMARY KEY,ok INTEGER NOT NULL CHECK(ok=1));

CREATE TABLE wealthfeed_connections (
 user_id TEXT PRIMARY KEY,
 encrypted_key TEXT NOT NULL,
 connection_id TEXT NOT NULL,
 connected_at TEXT NOT NULL,
 next_request_at BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE wealthfeed_jobs (
 id TEXT PRIMARY KEY,
 user_id TEXT NOT NULL,
 connection_id TEXT NOT NULL,
 provider_job_id TEXT,
 status TEXT NOT NULL,
 payload TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id, id)
);
CREATE INDEX idx_wealthfeed_jobs_user_created ON wealthfeed_jobs(user_id,created_at);
